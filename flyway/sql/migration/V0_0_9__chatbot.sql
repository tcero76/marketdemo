-- Schema y tabla de reservas del chatbot (PostgreSQL 10+).
-- Esta migración es la fuente de verdad del esquema: NO uses AutoMigrate de GORM en producción.
-- Es idempotente: se puede ejecutar más de una vez.

CREATE SCHEMA IF NOT EXISTS chatbot;

CREATE TABLE IF NOT EXISTS chatbot.reservas (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Identifica la conversación de origen. UNIQUE = una reserva por conversación,
    -- lo que hace seguro reintentar el guardado (idempotencia).
    session_id  TEXT        NOT NULL,

    nombre      TEXT        NOT NULL,
    email       TEXT        NOT NULL,
    fecha       DATE        NOT NULL,
    personas    SMALLINT    NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT reservas_session_id_key UNIQUE (session_id),
    CONSTRAINT reservas_nombre_chk     CHECK (char_length(btrim(nombre)) >= 2),
    CONSTRAINT reservas_email_chk      CHECK (email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    CONSTRAINT reservas_personas_chk   CHECK (personas BETWEEN 1 AND 10)
);

CREATE INDEX IF NOT EXISTS reservas_fecha_idx ON chatbot.reservas (fecha);

COMMENT ON TABLE  chatbot.reservas            IS 'Reservas capturadas por el chatbot (formulario "reserva").';
COMMENT ON COLUMN chatbot.reservas.session_id IS 'ID de la conversación del chatbot; único por reserva.';
COMMENT ON COLUMN chatbot.reservas.fecha      IS 'Fecha de la reserva (sin hora).';